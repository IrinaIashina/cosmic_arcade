import pygame
import sys


def main():
    pygame.init()
    screen = pygame.display.set_mode((800, 600))
    pygame.display.set_caption("Космическая Аркада")
    clock = pygame.time.Clock()#Создаём объект "часы" для контроля FPS (скорости игры)

    #Создаём основной объект игры, передаём ему экран для рисования   
    
    running = True  #Создаём флаг для управления игровым циклом
    while running:
        # Обрабатываем ВСЕ события, которые произошли с последнего кадра
        for event in pygame.event.get(): 
            if event.type == pygame.QUIT: #Если событие - "закрытие окна" (крестик)
                running = False
        
        #Получаем состояние ВСЕХ клавиш клавиатуры (какие нажаты сейчас)
        #Обновляем состояние игры: двигаем объекты, проверяем столкновения
        #Рисуем всю игру на экране

        #-----
        #Простая отрисовка для демонстрации
        screen.fill((50, 50, 100))  # Тёмно-синий фон
    
        # Рисуем простой прямоугольник
        pygame.draw.rect(screen, (255, 200, 0), (100, 100, 200, 100))
        #-------
        
        pygame.display.flip() #ОБНОВЛЯЕМ ЭКРАН - показываем всё, что нарисовали
        # Без этой строки вы ничего не увидите!PyGame использует двойную буферизацию:
        # - Мы рисуем на "скрытом" холсте. - flip() показывает этот холст игроку

        clock.tick(60)#ОГРАНИЧИВАЕМ FPS до 60 кадров в секунду
    
    pygame.quit()
    sys.exit()

if __name__ == "__main__": #Магическая строка: если этот файл запустили напрямую, а не импортировали
    main()
